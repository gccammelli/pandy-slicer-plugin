#!/usr/bin/env python3
"""Exercise the testbed plugin's real IPC in Android's app sandbox. Never prints."""
import argparse
import hashlib
import json
import re
import shlex
import subprocess
import sys
import time
import uuid
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'equivalence'))
from pandy_equiv import compare, profiles, safety

ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument('--serial', required=True)
ap.add_argument('--engine', choices=('bambu', 'orca'), default='orca')
ap.add_argument('--case', default='cube', help='a case smoke.py has run the official reference for')
ap.add_argument('--check', choices=('slice', 'resources', 'capabilities', 'server-refusal', 'stale-resources', 'unknown-engine'), default='slice')
args = ap.parse_args()
pkg = 'io.github.gccammelli.pandy.slicer.testbed'
if not re.fullmatch(r'[a-z0-9-]+', args.case) or not (ROOT / 'build/orca/smoke' / args.case / 'reference/out.gcode.3mf').is_file():
    raise SystemExit(f'Run smoke.py reference --case {args.case} first.')
token = args.engine + '-' + args.case + '-' + args.check + '-' + uuid.uuid4().hex[:8]
output = ROOT / 'build/orca/phones' / args.serial / token
output.mkdir(parents=True)
resources = ROOT / ('third_party/orcaslicer/resources' if args.engine == 'orca' else 'build/reference/resources')
lib = profiles.Presets(resources)
case = json.loads((ROOT / 'build/orca/smoke' / args.case / 'input/case.json').read_text())
request = dict(version=1, printer=case['printer'], process=case['process'], filaments=case['filaments'],
               process_overrides=case['process_overrides'], filament_overrides=case['filament_overrides'],
               printer_includes=lib.includes(case['printer']))
remote_input = f'cache/probe/input/{args.case}'
remote_output = f'cache/probe/output/{token}'


def adb(*command, **kwargs):
    return subprocess.run(['adb', '-s', args.serial, *command], capture_output=True, **kwargs)


def shell(script, **kwargs):
    result = adb('shell', '-T', 'run-as ' + pkg + ' sh -c ' + shlex.quote(script), **kwargs)
    if result.returncode:
        raise RuntimeError(result.stderr.decode(errors='replace'))
    return result.stdout


shell('mkdir -p ' + remote_input)
shell('cat > ' + remote_input + '/request.json', input=json.dumps(request).encode())
shell('cat > ' + remote_input + '/model.3mf', input=(ROOT / 'build/orca/smoke' / args.case / 'input/model.3mf').read_bytes())
engine = 'unknown' if args.check == 'unknown-engine' else args.engine
launch = adb('shell', shlex.join(['am', 'start', '-n', pkg + '/io.github.gccammelli.pandystudio.EngineProbeActivity',
                               '--es', 'engine_id', engine, '--es', 'case', args.case, '--es', 'check', args.check, '--es', 'token', token]))
if launch.returncode or b'Error:' in launch.stdout:
    raise RuntimeError((launch.stdout + launch.stderr).decode(errors='replace'))
start = time.monotonic()
while time.monotonic() - start < 16 * 60 + 30:
    result = adb('shell', '-T', 'run-as', pkg, 'cat', remote_output + '/result.json')
    if result.returncode == 0:
        try:
            response = json.loads(result.stdout)
            break
        except json.JSONDecodeError:
            pass  # The activity may still be writing the result file.
    time.sleep(1)
else:
    raise SystemExit('Phone probe did not report a result; inspect app logs.')
response['seconds'] = round(time.monotonic() - start, 2)
response['engine'] = args.engine
response['serial'] = args.serial
response['check'] = args.check
response['case'] = args.case
for filename in ('capabilities.json', 'out.gcode.3mf', 'resources.zip'):
    result = adb('shell', '-T', 'run-as', pkg, 'cat', remote_output + '/' + filename)
    if result.returncode == 0:
        (output / filename).write_bytes(result.stdout)
log = adb('shell', '-T', 'run-as', pkg, 'cat', 'cache/' + ('last-slice.log' if args.engine == 'bambu' else 'last-slice-orca.log'))
if log.returncode == 0:
    (output / 'slice.log').write_bytes(log.stdout)
if response['ok'] and args.check == 'slice':
    file = output / 'out.gcode.3mf'
    response['safety_problems'] = safety.problems(file)
    with zipfile.ZipFile(file) as z:
        actual = {n: z.read(n) for n in z.namelist() if compare.GCODE.fullmatch(n)}
        response['md5_verified'] = bool(actual) and all(hashlib.md5(b).hexdigest().upper() == z.read(n + '.md5').decode().strip().upper() for n, b in actual.items())
    response['raw_gcode_sha256'] = {n: hashlib.sha256(b).hexdigest() for n, b in actual.items()}
    if args.engine == 'orca':
        reference = compare.read(ROOT / 'build/orca/smoke' / args.case / 'reference/out.gcode.3mf')
        reference = {n: b for n, b in reference.items() if compare.GCODE.fullmatch(n)}
        def normalize(b):
            return re.sub(rb'(?m)^; generated by OrcaSlicer ([^\r\n]+?) on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2}\r?$', rb'; generated by OrcaSlicer \1 on <timestamp>', b)
        response['gcode_identical_except_timestamp'] = reference.keys() == actual.keys() and all(normalize(b) == normalize(actual[n]) for n, b in reference.items())
        response['differences'] = {n: compare.first_difference(normalize(b), normalize(actual.get(n, b''))) for n, b in reference.items() if normalize(b) != normalize(actual.get(n, b''))}
if response['ok'] and args.check == 'resources':
    archive = output / 'resources.zip'
    metadata = json.loads(response['text'])
    response['zip_sha256_verified'] = hashlib.file_digest(archive.open('rb'), 'sha256').hexdigest() == metadata['sha256']
(output / 'result.json').write_text(json.dumps(response, indent=2) + '\n')
print(json.dumps(response, indent=2))
print('Evidence:', output)
expected_errors = {'unknown-engine': 'Unsupported slicing engine', 'stale-resources': 'Engine resources changed', 'server-refusal': 'does not support server mode'}
if args.check in expected_errors:
    good = not response['ok'] and expected_errors[args.check] in response['text']
else:
    good = (response['ok'] and not response.get('safety_problems') and response.get('md5_verified', True)
            and response.get('zip_sha256_verified', True) and response.get('gcode_identical_except_timestamp', True))
if not good:
    raise SystemExit(1)
