#!/usr/bin/env python3
"""Generates traps.c from a failed link: every symbol the linker reports undefined (GUI code the CLI's sources
reference but the engine does not build) becomes a trap. A function trap prints the symbol and aborts; a data trap
is zero-filled storage (a vtable or typeinfo of a GUI class: using one crashes at once).

Usage: gen_traps.py <link log> <traps.c>   (the link must use -Wl,--no-demangle so the log holds mangled names)
The generated file lists each symbol with its demangled name, so the set of trapped GUI code is reviewable."""
import re
import subprocess
import sys

log, out = sys.argv[1], sys.argv[2]
names = set(re.findall(r"undefined reference to `([A-Za-z0-9_]+)'", open(log, errors="replace").read()))
# Relinking reports symbols the previous link did not get to: keep the traps generated before.
try:
    names |= set(re.findall(r"^(?:void|__attribute__\(\(aligned\(64\)\)\) char) ([A-Za-z0-9_]+)", open(out).read(), re.M))
except FileNotFoundError:
    pass
# A trap kept from an earlier link whose real definition is now compiled in must go.
names -= set(re.findall(r"multiple definition of `([A-Za-z0-9_]+)'", open(log, errors="replace").read()))
names = sorted(names)
demangled = subprocess.run(["c++filt"], input="\n".join(names), capture_output=True, text=True).stdout.splitlines() if names else []
DATA_PREFIXES = ("_ZTV", "_ZTI", "_ZTS", "_ZTT", "_ZGV")

lines = ["/* Generated by engine/tools/gen_traps.py from the engine's link: GUI symbols the CLI sources reference",
         " * but never need. Do not edit. Calling a trapped function aborts with its name. */",
         "#include <stdio.h>", "#include <stdlib.h>", "",
         "static void pandy_trap(const char *symbol) {",
         '    fprintf(stderr, "pandy-engine: unsupported GUI code reached: %s\\n", symbol);',
         "    abort();", "}", ""]
functions = data = 0
for name, pretty in zip(names, demangled):
    pretty_c = pretty.replace("*/", "* /")
    # Data: vtables, typeinfo and guards, and C++ variables (mangled, no parameter list). A plain C name is taken to
    # be a function, so using it aborts with its name rather than reading zeros.
    if name.startswith(DATA_PREFIXES) or (name.startswith("_Z") and "(" not in pretty):
        lines.append(f"/* {pretty_c} */\n__attribute__((aligned(64))) char {name}[4096];")
        data += 1
    else:
        lines.append(f"/* {pretty_c} */\nvoid {name}(void) {{ pandy_trap(\"{pretty_c.replace(chr(92), chr(92)*2).replace(chr(34), chr(92)+chr(34))}\"); }}")
        functions += 1
lines.append("")
open(out, "w").write("\n".join(lines))
print(f"{functions} function traps, {data} data traps -> {out}")
