package io.github.gccammelli.pandystudio.slicer

import io.github.gccammelli.pandystudio.io.Zip
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.jsonArray
import kotlin.test.*

class ServerPortTest {
    private val profiles = mapOf(
        "profiles/BBL/machine/Demo Printer.json" to """{"name":"Demo Printer","default_print_profile":"0.20mm Standard @Demo","include":["Demo template"]}""",
        "profiles/BBL/machine/Demo template.json" to """{"name":"Demo template","machine_start_gcode":"G28\nG29"}""",
        "profiles/BBL/process/0.20mm Standard @Demo.json" to "{}",
        "profiles/BBL/filament/Bambu PLA Basic @Demo.json" to """{"name":"PLA","filament_colour":["#FFFFFF"]}""",
        "profiles/BBL/filament/Generic PETG @Demo.json" to """{"name":"PETG","filament_colour":["#00FF00"]}""",
    )
    private val source = ProfileSource { profiles[it] }
    private fun request(settings: Map<String, String> = emptyMap()) = PhoneRequest("demo", 1, "model", "Demo Printer", "textured_plate", "PLA", "#123456", settings)
    private fun zip(vararg entries: Pair<String, String>) = Zip.write(entries.map { it.first to it.second.encodeToByteArray() }, true)
    private fun obj(bytes: ByteArray) = Json.parseToJsonElement(bytes.decodeToString()).jsonObject

    @Test fun bareModelReceivesPrinterAndFilamentWithoutWritingResources() {
        val model = zip("3D/3dmodel.model" to "<model/>")
        val job = ServerPort.prepare(request(mapOf("wall_loops" to "3")), model, source, "/engine/resources")
        val project = Zip.read(job.files.getValue("model.3mf"))
        assertEquals("Textured PEI Plate", obj(project.getValue("Metadata/project_settings.config")).getValue("curr_bed_type").jsonPrimitive.content)
        assertEquals("#123456", obj(job.files.getValue("filament.json")).getValue("filament_colour").toString().trim('[', ']', '"'))
        assertTrue("--wall-loops=3" in job.arguments); assertTrue("--arrange" in job.arguments)
        assertEquals(setOf("model.3mf", "machine.json", "process.json", "filament.json"), job.files.keys)
        assertTrue(profiles.values.none { it.contains("pandy process") })
        // Expected values are generated by generate-server-parity.py calling the Python server functions.
        val expected = Json.parseToJsonElement(javaClass.classLoader!!.getResourceAsStream("server-parity.json")!!.bufferedReader().readText()).jsonObject
        assertEquals(expected.getValue("project"), obj(project.getValue("Metadata/project_settings.config")))
        assertEquals(expected.getValue("machine"), obj(job.files.getValue("machine.json")))
        assertEquals(expected.getValue("process"), obj(job.files.getValue("process.json")))
        assertEquals(expected.getValue("filament"), obj(job.files.getValue("filament.json")))
        assertEquals(expected.getValue("arguments").jsonArray.map { it.jsonPrimitive.content }, job.arguments)
    }

    @Test fun samePrinterKeepsProjectAndChangesOnlySelectedBed() {
        val model = zip("3D/3dmodel.model" to "<model/>", "Metadata/project_settings.config" to """{"printer_settings_id":"Demo Printer","print_settings_id":"0.20mm Standard @Demo"}""",
            "Metadata/model_settings.config" to """<config><plate><metadata key="plater_id" value="1"/></plate><plate><metadata key="plater_id" value="2"/></plate></config>""")
        val job = ServerPort.prepare(request(), model, source, "/engine/resources")
        val entries = Zip.read(job.files.getValue("model.3mf"))
        assertEquals("G28\nG29", obj(entries.getValue("Metadata/project_settings.config")).getValue("machine_start_gcode").jsonPrimitive.content)
        val xml = entries.getValue("Metadata/model_settings.config").decodeToString()
        assertEquals(1, Regex("Textured PEI Plate").findAll(xml).count())
        assertFalse("--load-settings" in job.arguments); assertFalse("--arrange" in job.arguments)
    }

    @Test fun twoPlateTwoFilamentConversionMatchesPythonReference() {
        val cfg = """{"printer_settings_id":"Old Printer","print_settings_id":"0.20mm Standard @Old","filament_settings_id":["Bambu PLA Basic @Old","Generic PETG @Old"],"different_settings_to_system":["wall_loops"],"wall_loops":"4"}"""
        val xml = """<config><plate><metadata key="plater_id" value="1"/></plate><plate><metadata key="plater_id" value="2"/></plate></config>"""
        val model = zip("3D/3dmodel.model" to "<model/>", "Metadata/project_settings.config" to cfg, "Metadata/model_settings.config" to xml)
        val job = ServerPort.prepare(request().copy(plate = 2), model, source, "/engine/resources")
        val actual = Zip.read(job.files.getValue("model.3mf"))
        val expected = Json.parseToJsonElement(javaClass.classLoader!!.getResourceAsStream("server-parity.json")!!.bufferedReader().readText()).jsonObject.getValue("project_conversion").jsonObject
        assertEquals(expected.getValue("project"), obj(actual.getValue("Metadata/project_settings.config")))
        assertEquals(expected.getValue("model_settings").jsonPrimitive.content, actual.getValue("Metadata/model_settings.config").decodeToString())
        assertEquals(expected.getValue("machine"), obj(job.files.getValue("machine.json")))
        assertEquals(expected.getValue("process"), obj(job.files.getValue("process.json")))
        assertEquals(expected.getValue("filaments").jsonArray.map { it.jsonPrimitive.content }, job.arguments[job.arguments.indexOf("--load-filaments") + 1].split(';').map { it.substringAfterLast('/') })
    }

    @Test fun refusesUnsafeOrAmbiguousProjects() {
        assertFailsWith<IllegalArgumentException> { ServerPort.prepare(request(), byteArrayOf(1), source, "/engine/resources") }
        val model = zip("3D/3dmodel.model" to "<model/>", "Metadata/project_settings.config" to """{"post_process":["evil"]}""")
        assertFailsWith<IllegalArgumentException> { ServerPort.prepare(request(), model, source, "/engine/resources") }
    }

    @Test fun generatedProcessIsResolvedBeforeSlicingAndKeepsOverrides() {
        val indexed = profiles + mapOf(
            "profiles/BBL.json" to """{"machine_list":[],"filament_list":[],"process_list":[{"name":"0.20mm Standard @Demo","sub_path":"process/0.20mm Standard @Demo.json"},{"name":"base","sub_path":"process/base.json"}]}""",
            "profiles/BBL/process/0.20mm Standard @Demo.json" to """{"name":"0.20mm Standard @Demo","inherits":"base","wall_loops":"2"}""",
            "profiles/BBL/process/base.json" to """{"name":"base","outer_wall_speed":["200"],"post_process":["unsafe"]}""",
        )
        val job = ServerPort.prepare(request(), zip("3D/3dmodel.model" to "<model/>"), source, "/engine/resources")
        val changed = job.copy(files = job.files + ("process.json" to """{"inherits":"0.20mm Standard @Demo","wall_loops":"4"}""".encodeToByteArray()))
        val resolved = ServerPort.resolveProcess(changed, ProfileSource { indexed[it] })
        val process = obj(resolved.files.getValue("process.json"))
        assertEquals("4", process.getValue("wall_loops").jsonPrimitive.content)
        assertEquals("200", process.getValue("outer_wall_speed").jsonArray.first().jsonPrimitive.content)
        assertFalse("post_process" in process)
        assertEquals(changed.arguments, resolved.arguments)
        assertContentEquals(changed.files.getValue("model.3mf"), resolved.files.getValue("model.3mf"))
        assertFailsWith<IllegalArgumentException> { ServerPort.resolveProcess(changed, ProfileSource { if (it == "profiles/BBL.json") indexed[it] else null }) }
        // A file that is not in the trusted vendor index is not an accepted system preset.
        val unindexed = indexed + ("profiles/BBL.json" to """{"machine_list":[],"process_list":[],"filament_list":[]}""")
        assertFailsWith<IllegalArgumentException> { ServerPort.resolveProcess(changed, ProfileSource { unindexed[it] }) }
    }

    @Test fun editorRejectsProjectsWhoseSettingsItCannotPreserve() {
        val model = zip("3D/3dmodel.model" to "<model/>")
        PhoneProtocol.validateEditorModel(request(), model)
        assertFailsWith<IllegalArgumentException> { PhoneProtocol.validateEditorModel(request().copy(plate = 2), model) }
        val project = zip("3D/3dmodel.model" to "<model/>", "Metadata/model_settings.config" to "<config/>")
        assertFailsWith<IllegalArgumentException> { PhoneProtocol.validateEditorModel(request(), project) }
    }
}
